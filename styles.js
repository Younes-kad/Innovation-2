// Keep job categories within three quiet brand tones, including existing database jobs.
const jobTones = [
  { color: colors.petrol, background: colors.tealSoft },
  { color: colors.accentInk, background: colors.peach },
  { color: '#73501E', background: colors.sand },
];
export function jobTone(job) {
  const hash = [...(job.category || job.company || '')].reduce(
    (sum, char) => sum + char.codePointAt(0),
    0
  );
  return jobTones[hash % jobTones.length];
}

