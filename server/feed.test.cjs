const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createServer } = require('./index.cjs');

test('followed feed, opt-in privacy, company posts and persistent unread cursors', async () => {
  const server = createServer(':memory:');
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  async function req(route, method = 'GET', data, token, status = 200) {
    const response = await fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(data ? { body: JSON.stringify(data) } : {}) });
    const body = await response.json();
    assert.equal(response.status, status, `${method} ${route}: ${JSON.stringify(body)}`); return body;
  }
  const register = (email, role) => req('/auth/register', 'POST', { name: email.split('@')[0], email, role, password: 'password-12345', phone: '12345678', birthDate: '2000-01-01' });
  try {
    const author = await register('author@example.dk', 'young');
    const reader = await register('reader@example.dk', 'young');
    const stranger = await register('stranger@example.dk', 'young');
    const company = await register('company@example.dk', 'company');
    assert.equal((await req('/people', 'GET', null, reader.token)).length, 0);
    await req(`/follows/${author.user.id}`, 'POST', {}, reader.token, 403);
    const initial = await req('/profiles/me', 'GET', null, author.token);
    const discoverable = { ...initial, discoverable: true, headline: 'Min offentlige overskrift', about: 'Privat præsentation', visibility: { presentation: true, experiences: true, education: true, skills: true }, skills: ['Privat kompetence'] };
    await req('/profiles/me', 'PUT', discoverable, author.token);
    const people = await req('/people?q=author', 'GET', null, reader.token);
    assert.equal(people.length, 1);
    assert.equal(people[0].email, undefined);
    assert.equal(people[0].phone, undefined);
    assert.equal(people[0].headline, discoverable.headline);
    await req('/posts', 'POST', { text: 'Kun virksomheder', shared: true, followers: false }, author.token, 201);
    await req('/posts', 'POST', { text: 'Kun mig', shared: false, followers: false }, author.token, 201);
    await req('/posts', 'POST', { text: 'Til mine følgere', shared: false, followers: true }, author.token, 201);
    assert.equal((await req('/feed', 'GET', null, reader.token)).length, 0);
    await req(`/follows/${author.user.id}`, 'POST', {}, reader.token);
    await req(`/follows/${author.user.id}`, 'POST', {}, reader.token);
    const feed = await req('/feed', 'GET', null, reader.token);
    assert.equal(feed.length, 1);
    assert.equal(feed[0].text, 'Til mine følgere');
    assert.equal(feed[0].author.name, 'author');
    const preview = await req(`/profiles/${author.user.id}`, 'GET', null, reader.token);
    assert.equal(preview.about, undefined);
    assert.deepEqual(preview.skills, []);
    assert.equal(preview.posts.length, 1);
    assert.equal(preview.following, true);
    assert.equal((await req(`/profiles/${author.user.id}`, 'GET', null, stranger.token)).posts.length, 0);
    const snapshot = await req('/notifications', 'GET', null, reader.token);
    assert.equal(snapshot.counts.feed, 1);
    await req('/posts', 'POST', { text: 'Et nyere opslag', followers: true }, author.token, 201);
    await req('/notifications/read', 'POST', { section: 'feed', cursor: snapshot.cursors.feed }, reader.token);
    assert.equal((await req('/notifications', 'GET', null, reader.token)).counts.feed, 1);
    assert.equal((await req('/notifications', 'GET', null, stranger.token)).counts.feed, 0);
    const latest = await req('/notifications', 'GET', null, reader.token);
    await req('/notifications/read', 'POST', { section: 'feed', cursor: latest.cursors.feed }, reader.token);
    await req('/notifications/read', 'POST', { section: 'feed', cursor: 0 }, reader.token);
    assert.equal((await req('/notifications', 'GET', null, reader.token)).counts.feed, 0);
    await req('/notifications/read', 'POST', { section: 'feed', cursor: 999999 }, reader.token, 400);
    await req('/notifications/read', 'POST', { section: 'bogus', cursor: 0 }, reader.token, 400);
    await req('/profiles/me', 'PUT', { ...discoverable, discoverable: false }, author.token);
    assert.equal((await req('/feed', 'GET', null, reader.token)).length, 0);
    await req(`/profiles/${author.user.id}`, 'GET', null, reader.token, 403);
    await req('/profiles/me', 'PUT', discoverable, author.token);
    const ownerPosts = await req('/profiles/me', 'GET', null, author.token);
    const sharedPost = ownerPosts.posts.find(p => p.text === 'Et nyere opslag');
    await req(`/posts/${sharedPost.id}`, 'PUT', { text: 'Nu privat', followers: false }, author.token);
    assert.equal((await req('/feed', 'GET', null, reader.token)).length, 1);
    await req(`/follows/${author.user.id}`, 'DELETE', null, reader.token);
    assert.equal((await req('/feed', 'GET', null, reader.token)).length, 0);
    const businessProfile = await req('/profiles/me', 'GET', null, company.token);
    await req('/profiles/me', 'PUT', { ...businessProfile, discoverable: true }, company.token);
    await req('/posts', 'POST', { text: 'Nyt fra virksomheden', followers: true }, company.token, 201);
    await req(`/follows/${company.user.id}`, 'POST', {}, reader.token);
    assert.equal((await req('/feed', 'GET', null, reader.token))[0].author.role, 'company');
    const foreign = (await req('/profiles/me', 'GET', null, company.token)).posts[0];
    await req(`/posts/${foreign.id}`, 'DELETE', null, reader.token, 404);
    const publicCompany = await req(`/profiles/${company.user.id}`, 'GET', null, reader.token);
    assert.equal(publicCompany.posts[0].text, 'Nyt fra virksomheden');
    const beforeDeletion = await req('/notifications', 'GET', null, reader.token);
    await req('/notifications/read', 'POST', { section: 'feed', cursor: beforeDeletion.cursors.feed }, reader.token);
    await req(`/posts/${foreign.id}`, 'DELETE', null, company.token);
    await req('/posts', 'POST', { text: 'Nyt efter sletning', followers: true }, company.token, 201);
    assert.equal((await req('/notifications', 'GET', null, reader.token)).counts.feed, 1);
    await req(`/follows/${reader.user.id}`, 'POST', {}, reader.token, 403);
    await req('/feed', 'GET', null, null, 401);
  } finally { await new Promise(resolve => server.close(resolve)); }
});
